USE INSTACART_LAB;
USE ROLE LAB_ROLE;
USE SECONDARY ROLES NONE;
--run section by section, not Run All
CREATE OR REPLACE TASK RAW.CONSUME_ORDERS_TASK
  WAREHOUSE = 'LAB_WH'
  SCHEDULE  = '1 MINUTE'
  WHEN SYSTEM$STREAM_HAS_DATA('INSTACART_LAB.RAW.ORDERS_INCREMENTAL_STREAM') 
AS
  INSERT INTO STAGING.ORDERS_CONSUMED SELECT * EXCLUDE (METADATA$ACTION,METADATA$ISUPDATE,METADATA$ROW_ID) FROM INSTACART_LAB.RAW.ORDERS_INCREMENTAL_STREAM;
SHOW TASKS;
ALTER TASK RAW.CONSUME_ORDERS_TASK RESUME; --started
SELECT COUNT(*) FROM RAW.ORDERS_INCREMENTAL_STREAM;
SELECT COUNT(*) FROM STAGING.ORDERS_CONSUMED;
ALTER TASK RAW.CONSUME_ORDERS_TASK SUSPEND;
SELECT SCHEDULED_TIME, STATE ,ERROR_MESSAGE FROM TABLE(INFORMATION_SCHEMA.TASK_HISTORY(TASK_NAME => 'CONSUME_ORDERS_TASK')) ORDER BY SCHEDULED_TIME DESC;